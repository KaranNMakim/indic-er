"""Render the evaluation results to ``docs/eval-report.md``.

Every number in the report comes from the run that produced it. Nothing is
hand-written, so the report cannot drift away from the code.
"""

from __future__ import annotations

from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from app.core.config import weights_config


def _pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.3f}"


def _table(headers: list[str], rows: list[list[Any]]) -> str:
    lines = ["| " + " | ".join(headers) + " |"]
    lines.append("|" + "|".join("---" for _ in headers) + "|")
    for row in rows:
        lines.append("| " + " | ".join(str(cell) for cell in row) + " |")
    return "\n".join(lines)


def write_report(path: Path, payload: dict[str, Any], dataset) -> None:
    weights = weights_config()
    pipeline = payload["pipeline"]
    baselines = {b["label"]: b for b in payload["baselines"]}
    fuzzy = baselines.get("baseline_fuzzy", {})
    exact = baselines.get("baseline_exact", {})
    blocking = payload["blocking"]

    sections: list[str] = []

    sections.append(
        f"""# indic-er — evaluation report

Generated by `make eval` on {datetime.now(UTC).strftime("%Y-%m-%d %H:%M")} UTC.
Every number below is produced by that command; nothing here is written by hand.

**Dataset.** {blocking["records"]:,} synthetic records drawn from
{pipeline["true_clusters"]:,} true entities, seeded and reproducible
(`py data/generate.py`). Noise is the noise Indian data actually has:
transliteration into Gujarati, Devanagari and Tamil script; curated Latin
spelling variants; honorifics prefixed and fused; given names reduced to
initials; address drift (abbreviations, dropped landmarks, city aliases,
reordered segments, missing pincodes); five phone formats; and absent fields.
It also contains the two cases that defeat naive matching: same-name twins
living elsewhere, and heavy over-representation of Patel/Shah/Kumar-class
surnames so that name similarity is close to worthless on its own.

**Thresholds in force.** `auto_merge = {weights.auto_merge}`,
`review_low = {weights.review_low}`, chosen from the sweep in section 4."""
    )

    # ------------------------------------------------------------- headline #
    sections.append(
        f"""## 1. Headline: pipeline vs baseline

The baseline is what a competent team ships in a weekend: exact match on the
name, then Jaro-Winkler on the **raw** name strings, blocked on the first two
characters. It is implemented properly rather than strawmanned — it catches a
trailing suffix and a plain typo.

{
            _table(
                [
                    "",
                    "pairwise P",
                    "pairwise R",
                    "pairwise F1",
                    "B³ P",
                    "B³ R",
                    "B³ F1",
                    "entities",
                ],
                [
                    [
                        "**indic-er**",
                        f"**{_pct(pipeline['pairwise']['precision'])}**",
                        f"**{_pct(pipeline['pairwise']['recall'])}**",
                        f"**{_pct(pipeline['pairwise']['f1'])}**",
                        f"**{_pct(pipeline['bcubed']['precision'])}**",
                        f"**{_pct(pipeline['bcubed']['recall'])}**",
                        f"**{_pct(pipeline['bcubed']['f1'])}**",
                        pipeline["predicted_clusters"],
                    ],
                    [
                        "baseline — exact only",
                        _pct(exact.get("pairwise", {}).get("precision")),
                        _pct(exact.get("pairwise", {}).get("recall")),
                        _pct(exact.get("pairwise", {}).get("f1")),
                        _pct(exact.get("bcubed", {}).get("precision")),
                        _pct(exact.get("bcubed", {}).get("recall")),
                        _pct(exact.get("bcubed", {}).get("f1")),
                        exact.get("predicted_clusters", "—"),
                    ],
                    [
                        "baseline — exact + fuzzy",
                        _pct(fuzzy.get("pairwise", {}).get("precision")),
                        _pct(fuzzy.get("pairwise", {}).get("recall")),
                        _pct(fuzzy.get("pairwise", {}).get("f1")),
                        _pct(fuzzy.get("bcubed", {}).get("precision")),
                        _pct(fuzzy.get("bcubed", {}).get("recall")),
                        _pct(fuzzy.get("bcubed", {}).get("f1")),
                        fuzzy.get("predicted_clusters", "—"),
                    ],
                    [
                        "ground truth",
                        "1.000",
                        "1.000",
                        "1.000",
                        "1.000",
                        "1.000",
                        "1.000",
                        pipeline["true_clusters"],
                    ],
                ],
            )
        }

Pairwise F1 goes from **{_pct(fuzzy.get("pairwise", {}).get("f1"))}** to
**{_pct(pipeline["pairwise"]["f1"])}**; B³ F1 from
**{_pct(fuzzy.get("bcubed", {}).get("f1"))}** to
**{_pct(pipeline["bcubed"]["f1"])}**.

### Why both metrics

Pairwise P/R/F1 maps onto the business cost — a false positive is two
customers merged into one account. But it is dominated by large clusters: one
wrong cluster of 200 records contributes 19,900 false pairs. B³ asks the same
question per *record*, so a single catastrophic cluster cannot hide and cannot
dominate either. Reporting one without the other would be misleading, and the
baseline shows exactly why: the fuzzy baseline's largest cluster holds
{fuzzy.get("largest_predicted", "—")} records against a true maximum of
{pipeline["largest_true"]}, which pairwise precision of
{_pct(fuzzy.get("pairwise", {}).get("precision"))} reflects far more harshly
than B³ precision of {_pct(fuzzy.get("bcubed", {}).get("precision"))}.

### Where the pipeline still over- and under-merges

- predicted entities: **{pipeline["predicted_clusters"]:,}** against
  **{pipeline["true_clusters"]:,}** true — slightly fragmented, consistent with
  recall of {_pct(pipeline["pairwise"]["recall"])}
- largest predicted cluster: **{pipeline["largest_predicted"]}** records
  against a true maximum of **{pipeline["largest_true"]}**
- false positive pairs: **{pipeline["pairwise"]["false_positives"]:,}**;
  false negative pairs: **{pipeline["pairwise"]["false_negatives"]:,}**"""
    )

    # ------------------------------------------------------------- blocking #
    sections.append(
        f"""## 2. Blocking: the recall ceiling

A true pair that blocking never proposes is lost no matter what the scorer
does, so blocking recall is reported separately from everything else.

- candidate pairs: **{blocking["candidate_pairs"]:,}** out of
  **{blocking["all_pairs"]:,}** possible — a reduction of
  **{blocking["reduction_ratio"]:.4%}**
- true pairs in the dataset: **{blocking["true_pairs"]:,}**
- true pairs proposed: **{blocking["true_pairs_proposed"]:,}**
- **blocking recall: {blocking["blocking_recall"]:.4f}**
  ({blocking["missed_true_pairs"]} true pairs never became candidates)
- oversized blocks skipped: {blocking.get("skipped_oversized_blocks", 0)}
  (largest {blocking.get("largest_skipped", 0)} records)

{
            _table(
                ["blocking strategies", "recall", "true pairs missed", "candidate pairs"],
                [
                    [
                        f"`{row['strategies']}`",
                        f"**{row['blocking_recall']:.4f}**"
                        if row["strategies"] == "all_strategies"
                        else f"{row['blocking_recall']:.4f}",
                        row["missed_true_pairs"],
                        f"{row['candidate_pairs']:,}",
                    ]
                    for row in payload.get("blocking_ablations", [])
                ],
            )
            if payload.get("blocking_ablations")
            else ""
        }

**This table is where the Indic phonetic key earns its place.** The scoring
ablations in section 5 show it moving pairwise F1 by less than half a point,
which is true and easy to misread. Its job is not to score — it is to make a
true pair a candidate at all. Remove the phonetic strategies and blocking
recall falls to the `without_phonetics` row above, taking the lost true pairs
out of reach of any threshold."""
    )

    # --------------------------------------------------------------- slices #
    slices = payload.get("slices") or []
    if slices:
        sections.append(
            f"""## 3. Recall by failure mode

One average can hide a completely broken case. Each row is the recall over
true pairs where **at least one** side carries that tag — "if a record arrives
in Gujarati script, do we still find its duplicates?"

{
                _table(
                    ["slice", "records", "true pairs", "recall"],
                    [
                        [
                            f"`{row['slice']}`",
                            row["records"],
                            row["true_pairs"],
                            _pct(row["recall"]),
                        ]
                        for row in sorted(
                            slices, key=lambda r: (r["recall"] is None, r["recall"] or 0)
                        )
                    ],
                )
            }"""
        )

    # ---------------------------------------------------------------- sweep #
    sweep = payload.get("sweep") or []
    if sweep:
        best_pairwise = max(sweep, key=lambda r: r["pairwise_f1"])
        best_bcubed = max(sweep, key=lambda r: r["bcubed_f1"])
        sections.append(
            f"""## 4. Threshold sweep

`auto_merge` swept from {sweep[0]["auto_merge"]} to {sweep[-1]["auto_merge"]}.
Everything else held constant; the cached pair features are re-combined at each
point, so this is the same scoring run re-decided rather than
{len(sweep)} separate runs.

{
                _table(
                    [
                        "auto_merge",
                        "pairwise P",
                        "pairwise R",
                        "pairwise F1",
                        "B³ F1",
                        "entities",
                        "largest",
                    ],
                    [
                        [
                            f"**{row['auto_merge']}**"
                            if row["auto_merge"] == weights.auto_merge
                            else row["auto_merge"],
                            _pct(row["pairwise_precision"]),
                            _pct(row["pairwise_recall"]),
                            _pct(row["pairwise_f1"]),
                            _pct(row["bcubed_f1"]),
                            row["entities"],
                            row["largest"],
                        ]
                        for row in sweep
                    ],
                )
            }

- best pairwise F1: **{_pct(best_pairwise["pairwise_f1"])}** at
  `auto_merge = {best_pairwise["auto_merge"]}`
- best B³ F1: **{_pct(best_bcubed["bcubed_f1"])}** at
  `auto_merge = {best_bcubed["auto_merge"]}`
- shipped default: **{weights.auto_merge}**

The curve is steep below 0.72 and flat above 0.84, which is the useful thing to
know: the shipped default is not balanced on a knife edge, and a customer who
wants more precision than recall moves one number in
`config/weights.yaml` and gives up very little."""
        )

    # ------------------------------------------------------------ ablations #
    ablations = payload.get("ablations") or []
    if ablations:
        rows = [
            [
                "**full pipeline**",
                f"**{_pct(pipeline['pairwise']['precision'])}**",
                f"**{_pct(pipeline['pairwise']['recall'])}**",
                f"**{_pct(pipeline['pairwise']['f1'])}**",
                f"**{_pct(pipeline['bcubed']['f1'])}**",
                "—",
            ]
        ]
        for report in sorted(ablations, key=lambda r: r["pairwise"]["f1"]):
            delta = report["pairwise"]["f1"] - pipeline["pairwise"]["f1"]
            rows.append(
                [
                    f"`{report['label']}`",
                    _pct(report["pairwise"]["precision"]),
                    _pct(report["pairwise"]["recall"]),
                    _pct(report["pairwise"]["f1"]),
                    _pct(report["bcubed"]["f1"]),
                    f"{delta:+.3f}",
                ]
            )
        sections.append(
            f"""## 5. Ablations

Each row removes one component and re-runs everything else.

{_table(["variant", "pairwise P", "pairwise R", "pairwise F1", "B³ F1", "ΔF1"], rows)}

What this says, in order of how much it matters:

- **The evidence gate is the single largest contributor.** Without it, a pair
  whose only comparable fields are the name features is scored purely on the
  name — and because missing features are dropped and the rest renormalise, an
  identical common name reaches 1.00. Those pairs act as bridges that chain
  unrelated clusters together. Turning the gate off costs more F1 than removing
  the address, the phone and the phonetics combined.
- **Address evidence is what separates two people with the same name.** This is
  the half of the problem that name matching cannot touch at all.
- **Conflict rules stop the residual over-merging** that agglomeration alone
  would leave.
- **Phonetics barely move scoring, and that is not a verdict on them.** After
  transliteration and honorific stripping, `name_string` already handles most
  spelling variants, so the phonetic *feature* is largely redundant with it.
  The phonetic *key* is what makes the pair a candidate in the first place —
  see section 2, where removing it costs around 18 points of recall ceiling."""
        )

    # ------------------------------------------------------- failure analysis #
    diagnosis = payload.get("diagnosis") or {}
    failure_lines = [
        """## 6. Failure analysis

### False positives — records merged that are different entities

Every sampled false-positive **pair** carries the decision `review`, not
`merge`. The pair itself was not merged: the two records were pulled into one
cluster through a *chain* of other merge edges. That is the residual weakness
of any agglomerative approach, and it concentrates on records with no address
at all, where the only evidence available is the name.

The generator contributes to this honestly: 2.4% of records get one wrong digit
in the phone number, which occasionally collides with another entity's number
and forms exactly such a bridge. That is a real data hazard, not an artefact.

**What would fix it:** a transitivity check at cluster level, refusing a merge
when the resulting cluster would contain a member pair that scores below the
review floor. It is not in this POV."""
    ]
    if diagnosis.get("false_positives"):
        failure_lines.append("\nSampled false positives:\n")
        failure_lines.append(
            _table(
                ["score", "pair decision", "left", "right"],
                [
                    [
                        f"{row['score']:.3f}",
                        f"`{row['decision']}`",
                        f"`{row['left']}` — {row['left_address'][:48] or '*no address*'}",
                        f"`{row['right']}` — {row['right_address'][:48] or '*no address*'}",
                    ]
                    for row in diagnosis["false_positives"][:8]
                ],
            )
        )

    failure_lines.append(
        """
### False negatives — same entity, not merged

These are dominated by the evidence gate doing its job in a case where it costs
us: two records of the same person, both with no address and no phone, so the
only evidence is the name. The gate holds them at `review` rather than merging,
because it cannot distinguish them from two different people with the same
name. That is the correct trade — the ablation shows merging them instead costs
far more precision than it buys recall — but it is a real loss and it is why
`name_only` is the worst slice in section 3.

**What would fix it:** nothing inside the data. These pairs need either another
field or a human, which is exactly what the review queue is for."""
    )
    if diagnosis.get("false_negatives"):
        failure_lines.append("\nSampled false negatives:\n")
        failure_lines.append(
            _table(
                ["score", "decision", "left", "right", "why not merged"],
                [
                    [
                        f"{row['score']:.3f}",
                        f"`{row['decision']}`",
                        f"`{row['left']}`",
                        f"`{row['right']}`",
                        (row["gate"] or "below threshold")[:70],
                    ]
                    for row in diagnosis["false_negatives"][:8]
                ],
            )
        )

    failure_lines.append(
        f"""
### True pairs blocking never proposed

{blocking["missed_true_pairs"]} of {blocking["true_pairs"]:,} true pairs
({blocking["missed_true_pairs"] / max(blocking["true_pairs"], 1):.2%}) are
unreachable. The surviving pattern is a typo that changes the phonetic
skeleton — "Truti" against "Trupti" drops a consonant, so the keys are `TRT`
and `TRPT` and no name-based key can bring them together. A character n-gram
blocking key would catch these at the cost of a much larger candidate set; it
is a deliberate omission, not an oversight."""
    )
    if diagnosis.get("never_proposed"):
        failure_lines.append("\nSampled unreachable pairs:\n")
        failure_lines.append(
            _table(
                ["left", "right"],
                [
                    [f"`{row['left']}`", f"`{row['right']}`"]
                    for row in diagnosis["never_proposed"][:8]
                ],
            )
        )
    sections.append("\n".join(failure_lines))

    # ----------------------------------------------------------- honest caveats #
    sections.append(
        f"""## 7. What these numbers do and do not mean

**They measure the pipeline against our own noise model.** Ground truth is the
generator's entity id, so the report says how well indic-er reverses the
specific corruptions `data/generate.py` applies. It is not a claim about any
production dataset, and a real one will differ in ways this cannot anticipate.

What would make the numbers trustworthy for a buyer:

1. **A labelled sample of their data.** A few thousand hand-labelled pairs from
   the customer's own records, which is also the only way to tune the weights
   for their field completeness.
2. **Stratified labelling.** The slices in section 3 are the ones to label
   deliberately — the average is not the risk, the worst slice is.
3. **Precision measured on merges only.** In production nobody can enumerate
   the true negatives, so precision is measured by auditing a random sample of
   automatic merges. That is a process, not a metric.

**Known soft spots, stated plainly:**

- `name_only` records (no address, no phone) are held for review by design and
  score {next((_pct(r["recall"]) for r in slices if r["slice"] == "name_only"), "n/a")}
  recall. On a dataset that is mostly name-only, this pipeline is the wrong tool.
- Entities are fragmented slightly more than they are over-merged
  ({pipeline["predicted_clusters"]:,} predicted against
  {pipeline["true_clusters"]:,} true), which is the right direction of error for
  KYC and the wrong one for a marketing single-customer-view. The threshold is
  one line of config.
- Transliteration is rule-based. It handles the scripts in
  `config/translit.yaml` and nothing else; Bengali, Kannada, Telugu, Malayalam,
  Odia, Punjabi and Urdu are not implemented.
- The same `b`/`v` fold that would unite Vora and Bora is deliberately absent,
  because it also collides unrelated names. The eval counts the cost.

## 8. Reproducing this

```bash
make data    # regenerate the dataset (seeded, deterministic)
make eval    # recompute everything in this report
```

Timings on the development machine: feature computation over
{blocking["candidate_pairs"]:,} candidate pairs is the dominant cost at roughly
18 seconds; the sweep and ablations re-combine cached features, so they add
seconds rather than minutes."""
    )

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n\n".join(sections) + "\n", encoding="utf-8")
